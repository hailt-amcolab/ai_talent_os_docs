import { test } from 'node:test'
import assert from 'node:assert/strict'
import { totpEnrollment } from './supabase.ts'

test('native TOTP SVG may contain XML prolog; normalize without rejecting real Supabase response', () => {
  const raw = '<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by QR provider -->\n<svg xmlns="http://www.w3.org/2000/svg"><path /></svg>'
  const result = totpEnrollment({ id: 'fixture', totp: { qr_code: raw, secret: 'fixture-only' } })
  assert.equal(Buffer.from(result.qr.split(',')[1]!, 'base64').toString(), raw.slice(raw.indexOf('<svg')))
  assert.equal(result.secret, 'fixture-only')
  assert.throws(() => totpEnrollment({ id: 'fixture', totp: { qr_code: '<html />', secret: 'fixture' } }))
  assert.throws(() => totpEnrollment({ id: 'fixture', totp: { qr_code: '<svg />' } }))
})
